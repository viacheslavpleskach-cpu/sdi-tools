    """Кінцеві розділові знаки в переліках шляхів: рядки «диск 1\\…» → «;», «записи окремо …» → «.»."""
    re_ = t['re']
    for pi in range(240, 591):
        s = t['atext'](pi).strip()
        if s.startswith('– відповідного фрагмента') and s.endswith('PDF'):
            t['tail'](pi, lambda o: o + ';')
        elif re_.match(r'[Дд]иск 1', s):
            if s.endswith('mkv'): t['tail'](pi, lambda o: o + ';')
            elif s.endswith('.'): t['tail'](pi, lambda o: o[:-1] + ';')
        elif re_.match(r'[Зз]аписи окремо', s) and s.endswith('mkv'):
            t['tail'](pi, lambda o: o + '.')


