# ---------------------------------------------------------------- читання
def paras_docx(path):
    with zipfile.ZipFile(path) as z:
        root = ET.fromstring(z.read('word/document.xml'))
    out = []
    def walk(el, buf, ital):
        for ch in el:
            t = ch.tag
            if t in (W + 'del', W + 'moveFrom'):
                continue
            if t == W + 'r':
                rpr = ch.find(W + 'rPr')
                it = rpr is not None and rpr.find(W + 'i') is not None and \
                    rpr.find(W + 'i').get(W + 'val', 'true') not in ('0', 'false')
                for x in ch:
                    s = ''
                    if x.tag == W + 't':
                        s = x.text or ''
                    elif x.tag == W + 'tab':
                        s = '\t'
                    elif x.tag in (W + 'br', W + 'cr'):
                        s = ' '
                    elif x.tag == W + 'noBreakHyphen':
                        s = '\u2011'
                    if s:
                        if it and s.strip():
                            ital.append((len(buf[0]), len(buf[0]) + len(s)))
                        buf[0] += s
            elif t in (W + 'p',):
                continue
            else:
                walk(ch, buf, ital)
    intab = set()
    for tc in root.iter(W + 'tc'):
        for p in tc.iter(W + 'p'):
            intab.add(id(p))
    for p in root.iter(W + 'p'):
        buf, ital = [''], []
        walk(p, buf, ital)
        out.append((buf[0], ital, id(p) in intab))
    return out

def read_doc(path):
    ext = os.path.splitext(path)[1].lower()
    if ext == '.docx':
        return paras_docx(path)
    if ext in ('.rtf', '.doc', '.odt'):
        d = tempfile.mkdtemp()
        subprocess.run(['soffice', '--headless', '--convert-to', 'docx', '--outdir', d, path],
                       check=True, capture_output=True, timeout=180)
        f = [x for x in os.listdir(d) if x.endswith('.docx')][0]
        return paras_docx(os.path.join(d, f))
    txt = open(path, encoding='utf-8').read()
    return [(l, [], False) for l in txt.split('\n')]

# ---------------------------------------------------------------- цитати
def quote_spans(t, ital, minw):
    spans, st = [], []
    for i, ch in enumerate(t):
        if ch == '«':
            st.append(i)
        elif ch == '»' and st:
            a = st.pop()
            if not st and len(t[a:i].split()) >= minw:
                spans.append((a, i + 1))
    # незакрита лапка (цитата на кілька абзаців) — до кінця абзацу
    if st and len(t[st[0]:].split()) >= minw:
        spans.append((st[0], len(t)))
    for a, b in ital:
        spans.append((a, b))
    return spans

def inq(spans, a, b):
    return any(x <= a and b <= y for x, y in spans)

