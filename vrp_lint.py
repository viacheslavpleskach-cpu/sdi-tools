def report(path, paras, hits, inquote, dch, maxshow):
    words = sum(len(p[0].split()) for p in paras)
    out = [f'# vrp_lint — {os.path.basename(path)}', '',
           f'Абзаців: {len(paras)}, слів: {words}. Правил-шаблонів: {len(R)} + перевірки документа. '
           f'Знахідок поза цитатами: {sum(len(v) for v in hits.values())}; у цитатах (не правити): {sum(len(v) for v in inquote.values())}.', '']
    for grp in ('ТЕХН', 'МОВА', 'МОВА*'):
        g = [(k, v) for k, v in hits.items() if k[1] == grp]
        if not g:
            continue
        title = {'ТЕХН': 'Технічні правила (діють і в цитатах)', 'МОВА': 'Мовні правила (поза цитатами)',
                 'МОВА*': 'Довідково: займенники для перевірки на двозначність (розд. 1.6)'}[grp]
        out += [f'## {title}', '']
        for (rid, _, sec, desc), v in sorted(g, key=lambda x: (x[0][2], x[0][0])):
            out.append(f'### {rid} [звід {sec}] {desc} — {len(v)}')
            for loc, frag, mt in v[:maxshow]:
                out.append(f'- {loc}: …{frag}… [{mt}]')
            if len(v) > maxshow:
                out.append(f'- … ще {len(v) - maxshow} (усі — у --json)')
            out.append('')
    if dch:
        out += ['## Перевірки документа (скорочення, одноманітність, ПІБ, повтори)', '']
        for rid, sec, d in dch:
            out.append(f'- {rid} [звід {sec}] {d}')
        out.append('')
    if inquote:
        out += ['## У цитатах — мовно не правити (лише кількість)', '']
        for (rid, _, sec, desc), v in inquote.items():
            out.append(f'- {rid} [звід {sec}] {desc}: {len(v)} ({", ".join(sorted(set(l for l, _, _ in v))[:8])})')
        out.append('')
    out.append(MANUAL)
    return '\n'.join(out)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('file')
    ap.add_argument('--out')
    ap.add_argument('--json')
