# ---------------------------------------------------------------- перевірка документа
def doc_checks(paras):
    """Перевірки на рівні документа: скорочення, одноманітність, прізвища."""
    full = '\n'.join(p[0] for p in paras)
    res = []
    fulln = full.replace('\u00a0', ' ')
    intro = re.findall(r'\(далі\s*[–-]\s*([^)]+?)\)', full)
    for ab in set(intro):
        ab = ab.strip(' «»“”')
        stem = ab if len(ab) < 6 or ab.isupper() else ab[:-1]
        n = len(re.findall(r'(?<![\w])' + re.escape(stem) + (r'\w{0,3}' if stem != ab else '') + r'(?![\w])', full))
        if n <= 1:
            res.append(('D01', '5.4', f'скорочення «{ab}» уведено, але далі не вживається — увід вилучити'))
    for ab in ['ЗМІ', 'НСРД', 'ЕЦП', 'КМУ', 'ДСА', 'ГУ', 'ДРАЦС', 'ЄСІТС', 'КЦС', 'ПІБ', 'ЄДРСР', 'ЄСПЛ', 'ВККСУ', 'НАБУ',
               'ДБР', 'ЄРДР', 'КЕП', 'ТОВ', 'ФОП', 'ПДР', 'ВКЗ', 'КУпАП']:
        if re.search(r'(?<![\w])' + ab + r'(?![\w])', full) and not re.search(r'\(далі\s*[–-]\s*' + ab, full):
            res.append(('D02', '5.4', f'скорочення «{ab}» вживається без уводу «(далі – {ab})» — розкрити або увести (для загальновідомих — за практикою документа)'))
    if re.search(r'\bп\.п\.', full):
        res.append(('D02', '5.4', '«п.п.» → «підпункт»'))
    for a, b in [('ЦК України', 'ЦКУ'), ('ЦПК України', 'ЦПКУ'), ('КПК України', 'КПКУ'), ('ВККСУ', 'ВККС'),
                 ('Вища рада правосуддя', 'ВРП'), ('Конвенції', 'Конвенції про захист прав людини')]:
        if a in full and b in full and a != b:
            res.append(('D03', '6', f'різні форми в одному документі: «{a}» і «{b}» — звести до однієї (якщо уведено скорочення, повну назву не повторювати)'))
    # повна назва після уводу скорочення
    for m in re.finditer(r'([А-ЯІЇЄ][\w’\'\- ]{10,120}?)\s*\(далі\s*[–-]\s*([^)]+?)\)', full):
        name = ' '.join(m.group(1).split()[-4:])
        if len(name) > 12 and full.count(name) > 1 and full.find(name, m.end()) > 0:
            res.append(('D04', '5.4', f'після «(далі – {m.group(2).strip()})» повна назва («…{name}») трапляється знову — уживати скорочення'))
    # прізвища з ініціалами: різні основи
    fio = re.findall(r'\b([А-ЯІЇЄҐ][а-яіїєґ’\'-]{2,})\s?([А-ЯІЇЄҐ]\.[А-ЯІЇЄҐ]\.)', full)
    byini = {}
    for s, ini in fio:
        byini.setdefault(ini, set()).add(s)
    def base(s):
        return re.sub(r'(?:ового|евого|ого|ому|ими|ові|ою|ої|ій|ий|ом|ем|им|их|а|у|ю|і|я|є|е|и)$', '', s.lower())
    for ini, ss in byini.items():
        stems = {}
        for s in ss:
            stems.setdefault(base(s), set()).add(s)
        if len(stems) > 1:
            res.append(('D05', '9', f'з ініціалами {ini} трапляються різні прізвища: {", ".join(sorted(ss))} — звірити (типова помилка — прізвище скаржника замість судді)'))
    # «Отже» / «Таким чином» поруч, однакові слова-відсилання поспіль — варіювання
    sents = re.split(r'(?<=[.!?])\s+', full)
    for i in range(1, len(sents)):
        for w in ['Отже', 'Таким чином', 'Крім того', 'Водночас', 'Однак', 'зазначив', 'зазначила', 'вказав', 'Відповідно до', 'Згідно з']:
            if sents[i].startswith(w) and sents[i-1].startswith(w):
                res.append(('D06', '0', f'«{w}» у сусідніх реченнях — варіювати: «{sents[i][:60]}…»'))
    # дубльований фрагмент
    seen = {}
    for k, (p, *_x) in enumerate(paras, 1):
        for s in re.split(r'(?<=[.!?])\s+', p):
            if len(s) > 140:
                if s in seen and seen[s] != k:
                    res.append(('D07', '9', f'однакове речення в абзацах {seen[s]} і {k}: «{s[:70]}…» — перевірити, чи це не дубль'))
                seen.setdefault(s, k)
    # неоднакові написання (лапки-назви)
    names = re.findall(r'«([А-ЯІЇЄ][^«»]{2,40})»', full.replace('\u00a0', ' '))
    low = {}
    for n in names:
        low.setdefault(re.sub(r'\W', '', n.lower()), set()).add(n)
    for k, v in low.items():
        if len(v) > 1:
            res.append(('D08', '6', 'різні написання назви: ' + ' / '.join('«%s»' % x for x in sorted(v))))
    return res


def pos_doc_rules(paras):
    """Перевірки з прив'язкою до місця, що потребують контексту всього документа."""
    out = []   # (k0, s, e, rid, grp, sec, desc)
    texts = [p[0] for p in paras]
    full = '\n'.join(texts)
    # уведені скорочення
    intro = {}
    for m in re.finditer(r'\(далі\s*[–-]\s*([^)]+?)\)', full):
        key = m.group(1).strip(' «»“”')
        intro[key] = m.start()
        intro.setdefault(key.split()[0], m.start())
    off = [0]
    for t in texts:
        off.append(off[-1] + len(t) + 1)
    def kpos(gpos):
        import bisect
        k = bisect.bisect_right(off, gpos) - 1
        return k, gpos - off[k]
    # 1) скорочення без уводу (усі, правило користувача від 24.11.2026)
    skip = {'ІІ', 'ІІІ', 'IV', 'VI', 'IX', 'XI', 'XII', 'УРСР', 'СРСР'}
    seen = set()
    for m in re.finditer(r'(?<![\w«“-])([А-ЯІЇЄҐ][А-ЯІЇЄҐа-яіїєґ]{0,3}[А-ЯІЇЄҐ][А-ЯІЇЄҐ]{0,4})(?![\w’-])', full):
        ab = m.group(1)
        if ab in skip or re.fullmatch(r'[IVXLC]+', ab) or ab.lower() == ab:
            continue
        if not re.fullmatch(r'(?:[А-ЯІЇЄҐ]{2,7}|[А-ЯІЇЄҐ]{1,3}[а-яіїєґ]{1,2}[А-ЯІЇЄҐ]{1,4})', ab):
            continue
        if sum(ch.isupper() for ch in ab) < 2:
            continue
        if ab in intro and intro[ab] < m.start():
            continue
        if re.search(r'(?<![\w])' + re.escape(ab) + r'\s?:', full) or re.search(r'\b' + re.escape(ab.lower()) + r'\b', full) \
                or re.search(r'\b' + re.escape(ab[0] + ab[1:].lower()) + r'\b', full):
            continue
        line = texts[kpos(m.start())[0]]
        if len(re.findall(r'[а-яіїєґ]', line)) < 3:   # заголовок великими літерами
            continue
        if ab in seen:
            continue
        seen.add(ab)
        k, s0 = kpos(m.start())
        out.append((k, s0, s0 + len(ab), 'D02', 'МОВА', '5.4',
                    'скорочення без уводу «(далі – …)» — розкрити або увести (правило користувача від 24.11.2026: розкривати всі)'))
    # 2) повна назва після уводу скорочення
    for m in re.finditer(r'((?:[А-ЯІЇЄҐ]?[а-яіїєґ’\'-]+\s+){2,7})\(далі\s*[–-]\s*([^)]+?)\)', full):
        ab = m.group(2).strip(' «»“”')
        n = sum(ch.isupper() for ch in ab) if re.fullmatch(r'[А-ЯІЇЄҐа-яіїєґ]{2,8}', ab) and sum(ch.isupper() for ch in ab) >= 2 else 3
        words = [w for w in m.group(1).split() if len(w) > 2 and w not in ('про', 'для', 'щодо')]
        if len(words) < min(n, 3):
            continue
        words = words[-max(n, 3):] if n > 3 else words[-3:]
        stems = r'\s+'.join(re.escape(w[:max(4, len(w) - 3)]) + r'\w*' for w in words)
        for mm in re.finditer(stems, full[m.end():]):
            g = m.end() + mm.start()
            k, s0 = kpos(g)
            out.append((k, s0, s0 + len(mm.group(0)), 'D04', 'МОВА', '5.4',
                        f'після «(далі – {m.group(2).strip()})» повна назва повторюється — уживати скорочення'))
    # 3) прізвища на -іа: відмінювані форми
    for m in set(re.findall(r'\b([А-ЯІЇЄҐ][а-яіїєґ’]+і)а\s?[А-ЯІЇЄҐ]\.[А-ЯІЇЄҐ]\.', full)):
        for mm in re.finditer(r'\b' + m + r'(?:ї|ю|єю|я)\b', full):
            k, s0 = kpos(mm.start())
            out.append((k, s0, s0 + len(mm.group(0)), 'D09', 'МОВА', '2.3',
                        f'прізвище на -іа ({m}а) не відмінюється'))
    # 4) повтор слів-зв'язок і дієслів-відсилань в абзаці — варіювати
    REP = [r'\bщодо\b', r'\bзазначи(?:в|ла|ли|ло)\b', r'\bвказа(?:в|ла|ли|ло)\b', r'\b[Вв]ідповідно до\b', r'\b[Зз]гідно з\w?\b',
           r'\bзазначен\w+', r'\bвказан\w+', r'\bКрім того\b', r'\bОтже\b', r'\bВодночас\b', r'\bоднак\b|\bОднак\b', r'\bтакож\b|\bТакож\b']
    for k, t in enumerate(texts):
        for rx in REP:
            ms = list(re.finditer(rx, t))
            for a, b in zip(ms, ms[1:]):
                if b.start() - a.end() < 400:
                    out.append((k, b.start(), b.end(), 'D10', 'МОВА', '0',
                                f'«{b.group(0)}» повторюється поруч — варіювати (або «про» замість «щодо»)'))
    # 4а) вкладені лапки: внутрішні « і » → “ ”
    depth, carry, opened_at_start = 0, 0, False
    for k, t in enumerate(texts):
        # багатоабзацна цитата: глибина переходить на наступний абзац (не далі ніж на 40 абзаців)
        if depth and carry < 40 and opened_at_start:
            carry += 1
        else:
            depth, carry = 0, 0
        stack = []
        for i, ch in enumerate(t):
            if ch == '«':
                stack.append(i)
                if depth >= 1:
                    out.append((k, i, i + 1, 'T21', 'ТЕХН', '4.4', 'вкладені лапки всередині «…» — “…”'))
                depth += 1
            elif ch == '»' and depth:
                if depth >= 2:
                    out.append((k, i, i + 1, 'T21', 'ТЕХН', '4.4', 'вкладені лапки всередині «…» — “…”'))
                depth -= 1
                if stack:
                    stack.pop()
        if depth and stack:
            opened_at_start = stack[0] <= 3 or (carry > 0 and not stack)
        elif depth and carry:
            opened_at_start = True
        else:
            opened_at_start = False
    # 5) посилання в таблицях — без https://
    for k, p in enumerate(paras):
        if len(p) > 2 and p[2]:
            for mm in re.finditer(r'https?://', p[0]):
                out.append((k, mm.start(), mm.end(), 'T26', 'ТЕХН', '5.7', 'посилання в клітинці таблиці — без «https://» (низький пріоритет)'))
    return out

def run(path, minw=8, maxshow=40):
    paras = read_doc(path)
    hits = OrderedDict()
    inquote = OrderedDict()
    pkt = None
    pos = {}
    for k0, a, b, rid, grp, sec, desc in pos_doc_rules(paras):
        pos.setdefault(k0, []).append((a, b, rid, grp, sec, desc))
    for k, (t, ital, *_t) in enumerate(paras, 1):
        m = re.match(r'\s*(\d{1,3})\.\s', t)
        if m:
            pkt = m.group(1)
        if not t.strip():
            continue
        qs = quote_spans(t, ital, minw)
        for rid, grp, sec, desc, rx, flt in R:
            for mm in rx.finditer(t):
                if flt and not flt(t, mm):
                    continue
                a, b = mm.span()
                frag = t[max(0, a-35):min(len(t), b+35)].replace('\u00a0', '°').replace('\t', ' ')
                loc = f'абз. {k}' + (f' (п. {pkt})' if pkt else '')
                item = (loc, frag.strip(), mm.group(0))
                key = (rid, grp, sec, desc)
                if grp != 'ТЕХН' and inq(qs, a, b):
                    inquote.setdefault(key, []).append(item)
                else:
                    hits.setdefault(key, []).append(item)
        for a, b, rid, grp, sec, desc in pos.get(k - 1, []):
            frag = t[max(0, a-35):min(len(t), b+35)].replace('\u00a0', '°').replace('\t', ' ')
            item = (f'абз. {k}' + (f' (п. {pkt})' if pkt else ''), frag.strip(), t[a:b])
            key = (rid, grp, sec, desc)
            (inquote if grp != 'ТЕХН' and inq(qs, a, b) else hits).setdefault(key, []).append(item)
    dch = [d for d in doc_checks(paras) if d[0] not in ('D02', 'D04')]
    return paras, hits, inquote, dch

